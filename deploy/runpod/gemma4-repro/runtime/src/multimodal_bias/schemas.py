ImageLoadStatus = Literal["loaded", "missing", "unreadable", "corrupt"]
ImageFormat = Literal["jpeg", "png", "gif", "webp"]


@dataclass(frozen=True)
class ImageLoadResult:
    """Per-sample image IO result for inference inputs."""

    sample_id: str
    image_path: Path
    status: ImageLoadStatus
    image_bytes: bytes | None
    image_format: ImageFormat | None
    error_message: str | None


@dataclass(frozen=True)
class ImageLoadReport:
    """Ordered image IO results plus aggregate counts."""

    results: tuple[ImageLoadResult, ...]

    @property
    def success_count(self) -> int:
        return sum(result.status == "loaded" for result in self.results)

    @property
    def failure_count(self) -> int:
        return len(self.results) - self.success_count


