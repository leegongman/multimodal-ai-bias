"""Shared typed schema boundary for pipeline components."""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from types import MappingProxyType
from typing import Literal


@dataclass(frozen=True)
class DataLayoutReport:
    """Summary of a validated official Multimodal data layout."""

    data_root: Path
    train_rows: int
    test_rows: int
    sample_submission_rows: int


@dataclass(frozen=True)
class SampleRecord:
    """Typed record parsed from one official Multimodal test.csv row."""

    sample_id: str
    image_path: Path
    context: str
    question: str
    answers: tuple[str, str, str]
    row_number: int


EvidenceType = Literal[
    "stated_text_fact",
    "objective_visible_evidence",
    "elimination",
    "insufficient_evidence",
]
ReasonerLabel = Literal["0", "1", "2"]
ReasonerRiskFlag = Literal["invalid_parse", "protected_attribute_risk"]
ReasonerParseStatus = Literal[
    "valid",
    "source_failed",
    "missing_marker",
    "invalid_json",
    "invalid_schema",
    "invalid_label",
]


@dataclass(frozen=True)
class ReasonerOutputContract:
    """Prompt-level contract for parseable Reasoner model output."""

    labels: tuple[str, str, str]
    parse_marker: str
    fields: tuple[str, ...]
    evidence_types: tuple[EvidenceType, ...]


@dataclass(frozen=True)
class ReasonerPromptTemplate:
    """Versioned Reasoner prompt template loaded from configs/prompts."""

    version: str
    system_prompt: str
    user_template: str
    output_contract: ReasonerOutputContract
    evidence_types: tuple[EvidenceType, ...]
    forbidden_sole_support_cues: tuple[str, ...]


@dataclass(frozen=True)
class ReasonerPrompt:
    """Built prompt for one prediction sample."""

    sample_id: str
    prompt_version: str
    system_prompt: str
    user_prompt: str
    output_contract: ReasonerOutputContract


@dataclass(frozen=True)
class ReasonerOutput:
    """Schema-valid structured output generated by the Reasoner."""

    label: ReasonerLabel
    evidence: str
    evidence_type: EvidenceType
    uncertainty_signal: bool
    protected_attribute_risk: bool
    uncertainty_option_index: int
    schema_version: str


@dataclass(frozen=True)
class ParsedReasonerRecord:
    """One parsed Reasoner row, including invalid and source-failure states."""

    run_id: str
    sample_id: str
    parsed_label: ReasonerLabel | None
    evidence_summary: str | None
    evidence_type: EvidenceType | None
    uncertainty_signal: bool | None
    risk_flags: tuple[ReasonerRiskFlag, ...]
    parse_status: ReasonerParseStatus
    parse_error: str | None
    uncertainty_option_index: int | None = None
    schema_version: str | None = None


@dataclass(frozen=True)
class ReasonerParseResult:
    """Summary and ordered rows from parsing a raw Reasoner artifact."""

    parsed_reasoner_path: Path
    records: tuple[ParsedReasonerRecord, ...]
    total_samples: int
    valid_count: int
    invalid_count: int


@dataclass(frozen=True)
class VerifierOutputContract:
    """Prompt-level contract for parseable Verifier model output."""

    labels: tuple[str, str, str]
    parse_marker: str
    fields: tuple[str, ...]
